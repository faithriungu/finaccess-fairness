"""Generate api/schema.py (the Pydantic request schema) from the model package.

Run from the project root after packaging:
    python -m api.generate_schema

The schema is written to a plain Python file rather than built at runtime so
that reviewers can read every field, allowed category and bound, and so the API
can validate requests before the model is even loaded. tests/test_api.py fails
if the file falls out of step with models/model_package.joblib.
"""
from pathlib import Path

import joblib

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "models" / "model_package.joblib"
OUT = Path(__file__).resolve().parent / "schema.py"

# Hard validation limits (requests outside these are rejected with 422).
# They are deliberately wider than the training range: plausible values the
# model never saw are scored, but flagged with a warning in the response.
BINARY = {
    "disability_status", "income_from_farming", "income_from_regular_job",
    "income_from_casual_work", "income_from_own_business",
    "relies_on_family_support", "has_any_id", "owns_phone",
    "skipped_meals_last_month", "experienced_shock",
}
HARD_BOUNDS = {
    "age": (18, 120),
    "household_size": (1, 50),
    "num_income_sources": (0, 20),
    "income_last_month": (0, 10_000_000),
    "income_highest_month": (0, 10_000_000),
    "income_lowest_month": (0, 10_000_000),
}
DESCRIPTIONS = {
    "age": "Age in completed years (adults only).",
    "household_size": "Number of household members.",
    "num_income_sources": "Number of income sources reported.",
    "income_last_month": "Income received last month, KSh.",
    "income_highest_month": "Income in the highest-earning month, KSh.",
    "income_lowest_month": "Income in the lowest-earning month, KSh.",
}


def render(package):
    schema = package["input_schema"]
    lines = [
        '"""Request schema for the bank-use API.',
        "",
        "AUTO-GENERATED by `python -m api.generate_schema` from",
        "models/model_package.joblib. Do not edit by hand; regenerate instead.",
        "",
        f"Model version: {package['metadata']['model_version']}",
        '"""',
        "from typing import Literal, Optional",
        "",
        "from pydantic import BaseModel, ConfigDict, Field",
        "",
        f"MODEL_VERSION = {package['metadata']['model_version']!r}",
        f"FEATURES = {package['features']!r}",
        "",
        "# Training-data ranges: values outside these are accepted (within the",
        "# hard bounds in the schema) but returned with a warning.",
        "TRAINING_RANGES = {",
    ]
    for col, spec in schema["numeric"].items():
        lines.append(f"    {col!r}: ({spec['min']!r}, {spec['max']!r}),")
    lines += [
        "}",
        "",
        "",
        "class Respondent(BaseModel):",
        '    """One adult respondent. Every field is required but may be null',
        "    (null = not answered / not recorded, as in the survey). Gender is",
        '    deliberately not a field: the model does not use it."""',
        "",
        '    model_config = ConfigDict(extra="forbid")',
        "",
    ]
    for col in package["features"]:
        if col in schema["numeric"]:
            if col in BINARY:
                lines.append(
                    f"    {col}: Optional[Literal[0, 1]] = Field(..., "
                    f"description=\"1 = yes, 0 = no.\")"
                )
            else:
                lo, hi = HARD_BOUNDS[col]
                desc = DESCRIPTIONS.get(col, "")
                lines.append(
                    f"    {col}: Optional[float] = Field(..., ge={lo}, le={hi}, "
                    f"description={desc!r})"
                )
        else:
            allowed = schema["categorical"][col]["allowed"]
            literal = ", ".join(repr(v) for v in allowed)
            lines.append(f"    {col}: Optional[Literal[{literal}]] = Field(...)")
    lines += [
        "",
        "",
        "class BatchRequest(BaseModel):",
        '    model_config = ConfigDict(extra="forbid")',
        "",
        "    records: list[Respondent] = Field(..., min_length=1, max_length=500)",
        "",
    ]
    return "\n".join(lines)


def main():
    if not PACKAGE.exists():
        raise FileNotFoundError(f"{PACKAGE} not found. Run python -m src.run_pipeline first.")
    package = joblib.load(PACKAGE)
    missing = set(package["input_schema"]["numeric"]) - BINARY - set(HARD_BOUNDS)
    if missing:
        raise ValueError(f"Add hard bounds for new numeric features: {sorted(missing)}")
    OUT.write_text(render(package), encoding="utf-8")
    print(f"Wrote {OUT} ({len(package['features'])} fields, model {package['metadata']['model_version']})")


if __name__ == "__main__":
    main()
